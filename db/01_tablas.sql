-- Fichas de socio: cada usuario está amarrado a su cuenta del login (auth.users)
create table public.usuarios (
  id            uuid primary key references auth.users(id) on delete cascade,
  created_at    timestamptz not null default now(),
  nombre        text,
  telefono      text,
  municipio     text,
  es_comprador  boolean not null default true,   -- todos pueden comprar
  es_productor  boolean not null default false   -- vender se activa por elección
);

-- Cargas ofrecidas por los productores
create table public.productos (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  productor_id  uuid references public.usuarios(id) on delete cascade,
  producto      text,
  variedad      text,
  calidad       text,
  cantidad_kg   numeric,   -- renombrada a "cantidad" en la migración 04
  precio_kg     numeric,   -- renombrada a "precio" en la migración 04
  foto_url      text,
  municipio     text
);

-- Negocios entre comprador y productor
create table public.pedidos (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  producto_id   bigint references public.productos(id) on delete cascade,
  comprador_id  uuid references public.usuarios(id) on delete cascade,
  cantidad_kg   numeric,   -- renombrada a "cantidad" en la migración 04
  estado        text default 'pendiente'   -- todo pedido nace pendiente
);

-- El portero (RLS) queda activo en las tres tablas
alter table public.usuarios  enable row level security;
alter table public.productos enable row level security;
alter table public.pedidos   enable row level security;
