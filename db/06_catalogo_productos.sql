-- AgroDirecto · Migración 06: catálogo de productos de la zona
begin;

create table public.catalogo_productos (
  id            bigint generated by default as identity primary key,
  nombre        text not null unique,   -- lo que ve el productor
  nombre_sipsa  text,                   -- vacío = sin referencia SIPSA
  usa_calidad   boolean not null default false
);

alter table public.catalogo_productos enable row level security;

create policy "cualquiera ve el catalogo de productos"
  on public.catalogo_productos for select
  to anon, authenticated
  using (true);

